export const resources = { en: { translation: en }, de: { translation: de } } as const

export function detectLanguage(storage: Pick<Storage, 'getItem'> | undefined = typeof localStorage === 'undefined' ? undefined : localStorage, languages: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages): AppLanguage {
  const saved = storage?.getItem(LANGUAGE_STORAGE_KEY)
  if (saved === 'de' || saved === 'en') return saved
  return languages.some((language) => language.toLowerCase().startsWith('de')) ? 'de' : 'en'
}

void i18n.use(initReactI18next).init({
  resources,
  lng: detectLanguage(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'de'],
  initAsync: false,
  interpolation: { escapeValue: false },
})

function updateDocumentLanguage(language: string) {
  if (typeof document === 'undefined') return
  document.documentElement.lang = language === 'de' ? 'de' : 'en'
  document.title = 'Hamburg Whereabouts'
  document.querySelector<HTMLMetaElement>('meta[name="description"]')?.setAttribute(
    'content',
    i18n.t('meta.description'),
  )
}

updateDocumentLanguage(i18n.resolvedLanguage ?? i18n.language)
i18n.on('languageChanged', updateDocumentLanguage)

export async function changeLanguage(language: AppLanguage) {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
  await i18n.changeLanguage(language)
}

export function activeLanguage(): AppLanguage {
  return i18n.resolvedLanguage === 'de' ? 'de' : 'en'
}

export function formatDate(value: Date, options: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(activeLanguage(), options).format(value)
}

export function formatNumber(value: number, options?: Intl.NumberFormatOptions) {
  return new Intl.NumberFormat(activeLanguage(), options).format(value)
}

export function formatPercent(value: number) {
  return new Intl.NumberFormat(activeLanguage(), {
    style: 'percent',
    maximumFractionDigits: 1,
  }).format(value / 100)
}

